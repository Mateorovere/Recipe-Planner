"""Fake AI providers used across the test suite.

Every test in this repo runs against these fakes — never against a real AI API —
per the project's testing requirements. They implement the same interfaces as the
real providers so services/routes can't tell the difference.
"""

from __future__ import annotations

import re

from app.ai.base import (
    ImageProvider,
    LLMProvider,
    RecipeGenerationProvider,
    SpeechProvider,
    VisionProvider,
)
from app.ai.types import (
    GeneratedNutrition,
    GeneratedRecipe,
    GeneratedRecipeIngredient,
    GenerationFilters,
    ImageResult,
    IngredientQuantity,
    RawDetectedIngredient,
)
from app.core.exceptions import AIProviderError


class FakeVisionProvider(VisionProvider):
    def __init__(self, ingredients: list[RawDetectedIngredient] | None = None) -> None:
        self.ingredients = ingredients or [
            RawDetectedIngredient(name="tomato", confidence=0.96),
            RawDetectedIngredient(name="egg", confidence=0.94),
            RawDetectedIngredient(name="onion", confidence=0.91),
        ]

    async def detect_ingredients(
        self, image_bytes: bytes, mime_type: str
    ) -> list[RawDetectedIngredient]:
        return self.ingredients


class FakeSpeechProvider(SpeechProvider):
    def __init__(self, transcript: str = "I have chicken, rice, onions and garlic.") -> None:
        self.transcript = transcript

    async def transcribe(self, audio_bytes: bytes, mime_type: str) -> str:
        return self.transcript


class FakeLLMProvider(LLMProvider):
    """Extracts ingredients with a naive split instead of calling a real LLM."""

    def __init__(self, ingredients: list[RawDetectedIngredient] | None = None) -> None:
        self.forced_ingredients = ingredients

    async def extract_ingredients(self, text: str) -> list[RawDetectedIngredient]:
        if self.forced_ingredients is not None:
            return self.forced_ingredients
        cleaned = re.sub(r"^i have\s*", "", text.strip().lower())
        cleaned = cleaned.rstrip(".")
        parts = re.split(r",|\band\b", cleaned)
        return [RawDetectedIngredient(name=p.strip(), confidence=0.9) for p in parts if p.strip()]


class FailingLLMProvider(LLMProvider):
    """Used to test that ingredient extraction surfaces a clean error on AI failure."""

    async def extract_ingredients(self, text: str) -> list[RawDetectedIngredient]:
        raise AIProviderError("simulated failure")


class FakeRecipeGenerationProvider(RecipeGenerationProvider):
    """Generates one deterministic recipe using every given ingredient, plus one
    extra ingredient the user doesn't have (so tests can check missing/have
    flags). Configurable to simulate "the AI found nothing" or a hard failure."""

    def __init__(
        self,
        *,
        extra_ingredient: str = "salt",
        return_empty: bool = False,
        raise_error: bool = False,
    ) -> None:
        self.extra_ingredient = extra_ingredient
        self.return_empty = return_empty
        self.raise_error = raise_error
        self.last_call: tuple[list[IngredientQuantity], GenerationFilters | None, int] | None = None

    async def generate_recipes(
        self,
        ingredients: list[IngredientQuantity],
        *,
        filters: GenerationFilters | None,
        count: int,
    ) -> list[GeneratedRecipe]:
        self.last_call = (ingredients, filters, count)
        if self.raise_error:
            raise AIProviderError("simulated failure")
        if self.return_empty:
            return []

        recipe_ingredients = [
            GeneratedRecipeIngredient(
                name=i.name, quantity=i.quantity, unit=i.unit, importance="normal", user_has=True
            )
            for i in ingredients
        ]
        recipe_ingredients.append(
            GeneratedRecipeIngredient(
                name=self.extra_ingredient,
                quantity=None,
                unit=None,
                importance="critical",
                user_has=False,
            )
        )

        names = ", ".join(i.name for i in ingredients)
        return [
            GeneratedRecipe(
                title=f"Fake Recipe with {names}",
                description="A recipe generated by the test fake.",
                cuisine="Test Cuisine",
                difficulty="easy",
                prep_time_minutes=10,
                cook_time_minutes=15,
                servings=2,
                ingredients=recipe_ingredients,
                steps=["Combine everything.", "Cook until done."],
                nutrition=GeneratedNutrition(
                    calories=400.0, protein_g=20.0, carbs_g=40.0, fat_g=15.0, fiber_g=5.0
                ),
                tags=["quick", "dinner"],
                substitutions=[],
                match_explanation=f"You have {len(ingredients)} matching ingredients.",
            )
        ]


class FakeImageProvider(ImageProvider):
    """Returns a fixed result (or `None`, matching "no key configured") instead
    of calling Unsplash."""

    def __init__(self, result: ImageResult | None = None) -> None:
        self.result = result
        self.queries: list[str] = []

    async def find_image(self, query: str) -> ImageResult | None:
        self.queries.append(query)
        return self.result
