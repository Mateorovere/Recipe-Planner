"""The recipe retrieval pipeline.

Recipes are never generated by the LLM — they always come from the database. The
pipeline is: normalize ingredients -> candidate search -> ingredient-overlap scoring
-> optional AI reranking (best-effort, never required for a result) -> top-N.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.ai.base import LLMProvider, NutritionProvider
from app.ai.types import RecipeRerankCandidate
from app.core.exceptions import AIProviderError, NoMatchingRecipesError, NotFoundError
from app.models.enums import IngredientImportance, NutritionSource
from app.models.nutrition import NutritionInformation
from app.models.recipe import Recipe
from app.repositories.favorite_repository import FavoriteRepository
from app.repositories.ingredient_repository import IngredientRepository
from app.repositories.recipe_repository import RecipeRepository
from app.repositories.search_repository import SearchRepository
from app.schemas.recipe import (
    NutritionSchema,
    RecipeDetail,
    RecipeIngredientSchema,
    RecipeSearchFilters,
    RecipeSearchResponse,
    RecipeStepSchema,
    RecipeSummary,
    SubstitutionSchema,
)
from app.services.ingredient_normalization import IngredientNormalizer

logger = logging.getLogger(__name__)

_IMPORTANCE_WEIGHT = {
    IngredientImportance.CRITICAL: 3.0,
    IngredientImportance.NORMAL: 1.0,
    IngredientImportance.OPTIONAL: 0.4,
}


@dataclass
class _ScoredRecipe:
    recipe: Recipe
    matched_ingredient_names: list[str]
    missing_ingredient_names: list[str]
    matched_count: int
    total_count: int
    base_score: float
    explanation: str = ""


class RecipeService:
    def __init__(
        self,
        session: AsyncSession,
        *,
        llm_provider: LLMProvider,
        nutrition_provider: NutritionProvider,
        ai_rerank_enabled: bool,
    ) -> None:
        self._session = session
        self._llm = llm_provider
        self._nutrition = nutrition_provider
        self._ai_rerank_enabled = ai_rerank_enabled
        self._recipes = RecipeRepository(session)
        self._ingredients = IngredientRepository(session)
        self._normalizer = IngredientNormalizer(session)
        self._searches = SearchRepository(session)
        self._favorites = FavoriteRepository(session)

    # ------------------------------------------------------------------ search

    async def search(
        self,
        raw_ingredients: list[str],
        *,
        filters: RecipeSearchFilters | None,
        limit: int,
        user_id: int | None,
    ) -> RecipeSearchResponse:
        normalized = await self._normalizer.normalize_many(raw_ingredients)
        matched_ids = [n.ingredient.id for n in normalized if n.ingredient is not None]

        candidates = await self._recipes.find_candidates_by_ingredient_ids(matched_ids)
        scored = [self._score_recipe(recipe, set(matched_ids)) for recipe in candidates]
        scored = self._apply_filters(scored, filters)
        scored.sort(key=lambda s: s.base_score, reverse=True)
        scored = scored[:limit]

        ai_reranked = False
        if scored and self._ai_rerank_enabled:
            ai_reranked = await self._try_rerank(scored, [n.raw_name for n in normalized])

        await self._searches.record(
            user_id=user_id,
            query_ingredients=[n.raw_name for n in normalized],
            results_count=len(scored),
        )
        await self._session.commit()

        if not scored:
            raise NoMatchingRecipesError(
                "No recipes matched those ingredients yet. Try adding a few more, or "
                "broadening your list."
            )

        return RecipeSearchResponse(
            recipes=[self._to_summary(s) for s in scored], ai_reranked=ai_reranked
        )

    # ------------------------------------------------------------------ detail

    async def get_detail(
        self, recipe_id: int, *, raw_ingredients: list[str], user_id: int | None
    ) -> RecipeDetail:
        recipe = await self._recipes.get_by_id(recipe_id)
        if recipe is None:
            raise NotFoundError(f"Recipe {recipe_id} was not found.", code="recipe_not_found")

        matched_ids: set[int] = set()
        if raw_ingredients:
            normalized = await self._normalizer.normalize_many(raw_ingredients)
            matched_ids = {n.ingredient.id for n in normalized if n.ingredient is not None}

        scored = self._score_recipe(recipe, matched_ids)
        if raw_ingredients and self._ai_rerank_enabled:
            await self._try_rerank([scored], raw_ingredients)
        if not scored.explanation:
            scored.explanation = self._template_explanation(scored)

        nutrition = await self._get_or_estimate_nutrition(recipe)
        substitutions = await self._build_substitutions(recipe)
        is_favorited = (
            await self._favorites.is_favorited(user_id, recipe_id) if user_id is not None else False
        )

        summary = self._to_summary(scored)
        return RecipeDetail(
            **summary.model_dump(),
            cuisine=recipe.cuisine,
            ingredients=[
                RecipeIngredientSchema(
                    name=ri.ingredient.name,
                    quantity=ri.quantity,
                    unit=ri.unit,
                    importance=ri.importance,
                    have=ri.ingredient_id in matched_ids,
                )
                for ri in recipe.recipe_ingredients
            ],
            steps=[
                RecipeStepSchema(step_number=s.step_number, instruction=s.instruction)
                for s in recipe.steps
            ],
            nutrition=nutrition,
            match_explanation=scored.explanation,
            substitutions=substitutions,
            is_favorited=is_favorited,
        )

    # ------------------------------------------------------------------ scoring

    def _score_recipe(self, recipe: Recipe, matched_ids: set[int]) -> _ScoredRecipe:
        matched, missing = [], []
        weighted_have = 0.0
        weighted_total = 0.0
        for ri in recipe.recipe_ingredients:
            weight = _IMPORTANCE_WEIGHT[ri.importance]
            weighted_total += weight
            if ri.ingredient_id in matched_ids:
                matched.append(ri.ingredient.name)
                weighted_have += weight
            elif ri.importance != IngredientImportance.OPTIONAL:
                missing.append(ri.ingredient.name)

        base_score = (weighted_have / weighted_total) if weighted_total else 0.0
        return _ScoredRecipe(
            recipe=recipe,
            matched_ingredient_names=matched,
            missing_ingredient_names=missing,
            matched_count=len(matched),
            total_count=len(recipe.recipe_ingredients),
            base_score=base_score,
        )

    def _apply_filters(
        self, scored: list[_ScoredRecipe], filters: RecipeSearchFilters | None
    ) -> list[_ScoredRecipe]:
        if filters is None:
            return [s for s in scored if s.matched_count > 0]

        result = []
        wanted_tags = {t.lower() for t in filters.dietary_tags}
        for s in scored:
            if s.matched_count == 0:
                continue
            if filters.difficulty is not None and s.recipe.difficulty != filters.difficulty:
                continue
            if (
                filters.max_total_time_minutes is not None
                and s.recipe.total_time_minutes > filters.max_total_time_minutes
            ):
                continue
            if wanted_tags:
                recipe_tags = {t.tag.lower() for t in s.recipe.tags}
                if not wanted_tags.issubset(recipe_tags):
                    continue
            result.append(s)
        return result

    async def _try_rerank(self, scored: list[_ScoredRecipe], user_ingredients: list[str]) -> bool:
        """Best-effort AI reranking. Returns whether it actually ran."""
        try:
            results = await self._llm.rerank(
                [
                    RecipeRerankCandidate(
                        recipe_id=s.recipe.id,
                        title=s.recipe.title,
                        matched_ingredients=s.matched_ingredient_names,
                        missing_ingredients=s.missing_ingredient_names,
                        base_score=s.base_score,
                    )
                    for s in scored
                ],
                user_ingredients,
            )
        except AIProviderError as exc:
            logger.warning("AI rerank skipped after provider error: %s", exc)
            return False

        by_id = {r.recipe_id: r for r in results}
        for s in scored:
            result = by_id.get(s.recipe.id)
            if result is not None:
                s.base_score = result.adjusted_score
                s.explanation = result.explanation
        scored.sort(key=lambda s: s.base_score, reverse=True)
        return True

    @staticmethod
    def _template_explanation(scored: _ScoredRecipe) -> str:
        if not scored.missing_ingredient_names:
            return "You have everything this recipe needs."
        missing = ", ".join(scored.missing_ingredient_names[:3])
        return (
            f"You already have {scored.matched_count}/{scored.total_count} ingredients. "
            f"You're missing: {missing}."
        )

    @staticmethod
    def _to_summary(scored: _ScoredRecipe) -> RecipeSummary:
        recipe = scored.recipe
        percentage = (
            (scored.matched_count / scored.total_count * 100) if scored.total_count else 0.0
        )
        return RecipeSummary(
            id=recipe.id,
            title=recipe.title,
            slug=recipe.slug,
            image_url=recipe.image_url,
            description=recipe.description,
            prep_time_minutes=recipe.prep_time_minutes,
            cook_time_minutes=recipe.cook_time_minutes,
            total_time_minutes=recipe.total_time_minutes,
            difficulty=recipe.difficulty,
            servings=recipe.servings,
            match_percentage=round(percentage, 1),
            matched_ingredient_count=scored.matched_count,
            total_ingredient_count=scored.total_count,
            missing_ingredients=scored.missing_ingredient_names,
        )

    # ------------------------------------------------------------------ nutrition & substitutions

    async def _get_or_estimate_nutrition(self, recipe: Recipe) -> NutritionSchema | None:

        # Queried directly (rather than via `recipe.nutrition`) so this is correct
        # even when `recipe` was loaded earlier in a long-lived session and a
        # nutrition row has since been persisted for it.
        existing = await self._session.execute(
            select(NutritionInformation).where(NutritionInformation.recipe_id == recipe.id)
        )
        record = existing.scalar_one_or_none()
        if record is not None:
            return NutritionSchema(
                calories=record.calories,
                protein_g=record.protein_g,
                carbs_g=record.carbs_g,
                fat_g=record.fat_g,
                fiber_g=record.fiber_g,
                source=record.source,
            )
        try:
            estimate = await self._nutrition.estimate(
                title=recipe.title,
                ingredients=[ri.ingredient.name for ri in recipe.recipe_ingredients],
                servings=recipe.servings,
            )
        except AIProviderError as exc:
            logger.warning("Nutrition estimate unavailable for recipe %s: %s", recipe.id, exc)
            return None

        record = NutritionInformation(
            recipe_id=recipe.id,
            calories=estimate.calories,
            protein_g=estimate.protein_g,
            carbs_g=estimate.carbs_g,
            fat_g=estimate.fat_g,
            fiber_g=estimate.fiber_g,
            source=NutritionSource.AI_GENERATED,
        )
        self._session.add(record)
        await self._session.commit()
        return NutritionSchema(
            calories=record.calories,
            protein_g=record.protein_g,
            carbs_g=record.carbs_g,
            fat_g=record.fat_g,
            fiber_g=record.fiber_g,
            source=record.source,
        )

    async def _build_substitutions(self, recipe: Recipe) -> list[SubstitutionSchema]:
        ingredient_ids = [ri.ingredient_id for ri in recipe.recipe_ingredients]
        subs = await self._ingredients.list_substitutions_for(ingredient_ids)
        if not subs:
            return []
        substitute_ids = [s.substitute_ingredient_id for s in subs]
        substitute_by_id = {i.id: i for i in await self._ingredients.get_by_ids(substitute_ids)}
        by_id = {ri.ingredient_id: ri.ingredient.name for ri in recipe.recipe_ingredients}
        result = []
        for s in subs:
            substitute = substitute_by_id.get(s.substitute_ingredient_id)
            original_name = by_id.get(s.ingredient_id)
            if substitute is None or original_name is None:
                continue
            result.append(
                SubstitutionSchema(
                    ingredient=original_name, substitute=substitute.name, notes=s.notes
                )
            )
        return result
