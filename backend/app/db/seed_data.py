class RecipeIngredientSeed(TypedDict):
    name: str
    quantity: float | None
    unit: str | None
    importance: IngredientImportance


class RecipeSeed(TypedDict):
    title: str
    slug: str
    description: str
    image_url: str | None
    prep_time_minutes: int
    cook_time_minutes: int
    difficulty: Difficulty
    servings: int
    cuisine: str | None
    tags: list[str]
    ingredients: list[RecipeIngredientSeed]
    steps: list[str]
    nutrition: dict[str, float]


Importance = Literal["critical", "normal", "optional"]


def _ing(
    name: str, quantity: float | None, unit: str | None, importance: Importance
) -> RecipeIngredientSeed:
    return {
        "name": name,
        "quantity": quantity,
        "unit": unit,
        "importance": IngredientImportance(importance),
    }


